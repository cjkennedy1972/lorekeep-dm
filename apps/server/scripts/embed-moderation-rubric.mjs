import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  CATEGORIES,
  REQUIRED_TAGS,
  parseRubric,
} from '../../../scripts/moderation-rubric.mjs';

export const RUBRIC_SOURCE = fileURLToPath(
  new URL('../../../docs/security/moderation-rubric.md', import.meta.url),
);
export const GENERATED_PATH = fileURLToPath(
  new URL('../src/safety/moderationRubric.generated.ts', import.meta.url),
);

export function renderRubricModule(markdown) {
  const sections = parseRubric(markdown);
  const body = {};
  for (const tag of REQUIRED_TAGS) {
    if (!sections.has(tag)) throw new Error(`missing rubric section: ${tag}`);
    body[tag] = sections.get(tag);
  }
  return (
    '// Generated by apps/server/scripts/embed-moderation-rubric.mjs from docs/security/moderation-rubric.md. Do not edit.\n' +
    `export const MODERATION_SECTIONS = ${JSON.stringify(body, null, 2)} as const;\n\n` +
    `export const MODERATION_CATEGORIES = ${JSON.stringify(CATEGORIES, null, 2)} as const;\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(
    GENERATED_PATH,
    renderRubricModule(readFileSync(RUBRIC_SOURCE, 'utf8')),
  );
}
